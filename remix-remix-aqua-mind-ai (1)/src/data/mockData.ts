// Helper to calculate dynamic scenarios matching any custom or preset total demand
export function getScenariosForFacilities(facs: Facility[]): ScarcityScenario[] {
  const totalDemand = facs.reduce((sum, f) => sum + f.demandLiters, 0);
  const totalMin = facs.reduce((sum, f) => sum + f.minLiters, 0);
  const capacity = Math.max(500000, Math.round((totalDemand * 4.5) / 10000) * 10000);

  return [
    {
      id: 'normal',
      name: 'Normal Supply',
      badge: `${Math.round(((1.05 * totalDemand) / totalDemand) * 100)}% of Demand`,
      supplyLiters: Math.round((totalDemand * 1.05) / 1000) * 1000,
      incomingSupplyLiters: Math.round((totalDemand * 1.05) / 1000) * 1000,
      currentStoredLiters: Math.round((capacity * 0.9) / 1000) * 1000,
      reservoirCapacityLiters: capacity,
      assumptions:
        'Full baseline municipal inflow. No drought restrictions. Reservoir is at 90% capacity and sufficient for all daily demands across all societies, hospital, and company.',
      severityColor: 'emerald',
    },
    {
      id: 'moderate',
      name: 'Moderate Scarcity',
      badge: '75% of Demand',
      supplyLiters: Math.round((totalDemand * 0.75) / 1000) * 1000,
      incomingSupplyLiters: Math.round((totalDemand * 0.7) / 1000) * 1000,
      currentStoredLiters: Math.round((capacity * 0.65) / 1000) * 1000,
      reservoirCapacityLiters: capacity,
      assumptions: `Tier-1 drought advisory. Supply curtailed by 25% (${Math.round(totalDemand * 0.25).toLocaleString()} L/day deficit). Discretionary irrigation restricted; critical facilities protected.`,
      severityColor: 'amber',
    },
    {
      id: 'severe',
      name: 'Severe Scarcity',
      badge: `${Math.round(((totalMin * 1.05) / totalDemand) * 100)}% of Demand`,
      supplyLiters: Math.round((totalMin * 1.05) / 1000) * 1000,
      incomingSupplyLiters: Math.round((totalMin * 0.95) / 1000) * 1000,
      currentStoredLiters: Math.round((capacity * 0.35) / 1000) * 1000,
      reservoirCapacityLiters: capacity,
      assumptions: `Tier-2 regional drought crisis. Supply (${Math.round(totalMin * 1.05).toLocaleString()} L) is near the community minimum threshold (${totalMin.toLocaleString()} L). Essential baselines barely covered.`,
      severityColor: 'orange',
    },
    {
      id: 'critical',
      name: 'Critical Shortage',
      badge: `${Math.round(((totalMin * 0.75) / totalDemand) * 100)}% of Demand (Sub-Minimum)`,
      supplyLiters: Math.round((totalMin * 0.75) / 1000) * 1000,
      incomingSupplyLiters: Math.round((totalMin * 0.65) / 1000) * 1000,
      currentStoredLiters: Math.round((capacity * 0.15) / 1000) * 1000,
      reservoirCapacityLiters: capacity,
      assumptions: `Emergency feeder outage. Supply (${Math.round(totalMin * 0.75).toLocaleString()} L/day) is strictly BELOW the total minimum requirements (${totalMin.toLocaleString()} L/day). Mandatory rationing activated; all minimums cannot be met.`,
      severityColor: 'rose',
    },
  ];
}

